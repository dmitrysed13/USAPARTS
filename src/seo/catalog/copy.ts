function car(model: CatalogModel): string {
  return `${model.brand} ${model.name}`;
}

function drive(model: CatalogModel): "ev" | "hybrid" | "ice" {
  if (model.slug === "prius") return "hybrid";
  if (model.body === "ev" || model.priorities.includes("batareya")) return "ev";
  return "ice";
}

function generations(model: CatalogModel): string {
  return model.generations.map((item) => item.label).join(", ");
}

