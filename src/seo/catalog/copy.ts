export function partCopy(model: CatalogModel, category: PartCategory): PartCopy {
  const angle = angles[category.slug];
  const name = car(model);
  const kind = drive(model);
  const power = kind === "ice" ? "" : (angle?.power?.[kind] ?? "");
  const focus = `На этой странице ищем «${category.h1}» для ${name}. Учитываем поколения: ${generations(model)}. ${model.note}`;
  const variantText = angle?.variants ?? category.subcategories.join(", ");
  const variants = [`«${category.h1}» для ${name}. ${variantText}`, power].filter(Boolean).join(" ");
  const vin = `Для «${category.h1}» на ${name} нужны и VIN, и OEM. ${angle?.vin ?? "Номер сверяем по коду."}`;
  const used = `${angle?.used ?? "Состояние пишем до оплаты."} Речь о заказе «${category.h1}» для ${name} из США.`;
  const ask = `Менеджеру по ${name} для «${category.h1}» напишите следующее. ${angle?.ask ?? category.ask}`;
  const order = `Заявку на «${category.h1}» для ${name} оставляете на этой странице. После выкупа в США доставка занимает от 15 до 30 дней, выдача в Бресте или отправка по Беларуси.`;
  return {
    lead: `«${category.h1}» для ${name}. В заявке: ${category.ask}. Номер подтверждаем VIN или OEM.`,
    description: `${category.h1} ${name} из США. В заявке: ${category.ask}. Поколения: ${generations(model)}. Доставка в Беларусь.`,
    sections: [
      { heading: `«${category.h1}» для ${name}`, paragraphs: [focus] },
      { heading: `Какие бывают варианты: ${category.h1}`, paragraphs: [variants] },
      { heading: `VIN и OEM для «${category.h1}»`, paragraphs: [vin] },
      { heading: `Новая и б/у: ${category.h1}`, paragraphs: [used] },
      { heading: `Что сообщить по «${category.h1}»`, paragraphs: [ask] },
      { heading: `Доставка «${category.h1}» в Беларусь`, paragraphs: [order] },
    ],
    faq: [
      { question: `Как заказать «${category.h1}» для ${name}?`, answer: ask },
      { question: `Можно ли взять «${category.h1}» от другого поколения ${model.name}?`, answer: `${model.note} ${vin}` },
      { question: `Чем новая «${category.h1}» отличается от б/у для ${name}?`, answer: used },
      { question: `Что прислать для подбора «${category.h1}» ${model.name}?`, answer: `${ask} ${category.ask}.` },
    ],
  };
}

